-- ZenithXI (modules\zenith-public\lua\4-additive\trusts\halver_override.lua).
--

describe('Trust: HALVER Integration Test #trusts #halver', function()
    ---@type CClientEntityPair
    local player
    assert(xi.settings.map.TRUST_SKILLS_BY_LEVEL == true, 'Zenith: TRUST_SKILLS_BY_LEVEL Must be set to true')

    before_each(function()
        player = xi.test.world:spawnPlayer({ zone = xi.zone.WEST_RONFAURE, job = xi.job.WAR, level = 1 })
        player:setGMLevel(5)
    end)

    it('Trust spell check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasSpell(xi.magic.spell.CURE))
        assert(not trustEntity:hasSpell(xi.magic.spell.FLASH))
        assert(not trustEntity:hasSpell(xi.magic.spell.CURE_IV))

        player:clearTrusts()
        player:setLevel(45)
        trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 45, 'Must be lv 45')
        assert(trustEntity:hasSpell(xi.magic.spell.CURE))
        assert(trustEntity:hasSpell(xi.magic.spell.FLASH))
        assert(not trustEntity:hasSpell(xi.magic.spell.CURE_IV))

        player:clearTrusts()
        player:setLevel(55)
        trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 55, 'Must be lv 55')
        assert(trustEntity:hasSpell(xi.magic.spell.CURE))
        assert(trustEntity:hasSpell(xi.magic.spell.FLASH))
        assert(trustEntity:hasSpell(xi.magic.spell.CURE_IV))
    end)

    it('Trust skill check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.RAMPART))
        assert(not trustEntity:hasLearnedAbility(xi.ja.BERSERK))
        assert(not trustEntity:hasLearnedAbility(xi.ja.SENTINEL))

        player:clearTrusts()
        player:setLevel(10)
        trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 10, 'Must be lv 10')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.RAMPART))
        assert(not trustEntity:hasLearnedAbility(xi.ja.BERSERK))
        assert(not trustEntity:hasLearnedAbility(xi.ja.SENTINEL))

        player:clearTrusts()
        player:setLevel(30)
        trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 30, 'Must be lv 30')
        assert(not trustEntity:hasLearnedAbility(xi.ja.RAMPART))
        assert(trustEntity:hasLearnedAbility(xi.ja.BERSERK))
        assert(trustEntity:hasLearnedAbility(xi.ja.SENTINEL))

        player:clearTrusts()
        player:setLevel(62)
        trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 62, 'Must be lv 62')
        assert(trustEntity:hasLearnedAbility(xi.ja.RAMPART))
    end)

    it('Trust trait check', function()
        local trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(trustEntity:getMod(xi.mod.DOUBLE_ATTACK) == 0)

         player:clearTrusts()
        player:setLevel(15)
        trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 15, 'Must be lv 15')
        assert(trustEntity:getMod(xi.mod.DOUBLE_ATTACK) >= 10)
    end)

    it('Trust WS check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.DOUBLE_THRUST))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.IMPULSE_DRIVE))

        player:clearTrusts()
        player:setLevel(5)
        trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 5, 'Must be lv 5')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.DOUBLE_THRUST))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.IMPULSE_DRIVE))

        player:clearTrusts()
        player:setLevel(56)
        trustEntity = player:spawnTrust(xi.magic.spell.HALVER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 56, 'Must be lv 56')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.DOUBLE_THRUST))
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.RAIDEN_THRUST))
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.PENTA_THRUST))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.IMPULSE_DRIVE))
    end)
end)
