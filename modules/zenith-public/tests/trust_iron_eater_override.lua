-- ZenithXI (modules\zenith-public\lua\4-additive\trusts\IRON_EATER_override.lua).
--

describe('Trust: IRON EATER Integration Test #trusts #iron_eater', function()
    ---@type CClientEntityPair
    local player
    assert(xi.settings.map.TRUST_SKILLS_BY_LEVEL == true, 'Zenith: TRUST_SKILLS_BY_LEVEL Must be set to true')

    before_each(function()
        player = xi.test.world:spawnPlayer({ zone = xi.zone.WEST_RONFAURE, job = xi.job.WAR, level = 1 })
        player:setGMLevel(5)
    end)

    it('Trust skill check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.RAMPART))
        assert(not trustEntity:hasLearnedAbility(xi.ja.BERSERK))
        assert(not trustEntity:hasLearnedAbility(xi.ja.SENTINEL))

        player:clearTrusts()
        player:setLevel(5)
        trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 5, 'Must be lv 5')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.BERSERK))

        player:clearTrusts()
        player:setLevel(15)
        trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 15, 'Must be lv 15')
        assert(trustEntity:hasLearnedAbility(xi.ja.BERSERK))
    end)

    it('Trust trait check', function()
        local trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(trustEntity:getMod(xi.mod.STORETP) == 0)
        assert(trustEntity:getMod(xi.mod.DOUBLE_ATTACK) == 0)

        player:clearTrusts()
        player:setLevel(10)
        trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 10, 'Must be lv 10')
        assert(trustEntity:getMod(xi.mod.STORETP) >= 10)
        assert(trustEntity:getMod(xi.mod.DOUBLE_ATTACK) == 0)

        player:clearTrusts()
        player:setLevel(15)
        trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 15, 'Must be lv 15')
        assert(trustEntity:getMod(xi.mod.STORETP) >= 10)
        assert(trustEntity:getMod(xi.mod.DOUBLE_ATTACK) == 0)

        player:clearTrusts()
        player:setLevel(25)
        trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 25, 'Must be lv 25')
        assert(trustEntity:getMod(xi.mod.STORETP) >= 10)
        assert(trustEntity:getMod(xi.mod.DOUBLE_ATTACK) >= 10)
    end)

    it('Trust WS check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.SHIELD_BREAK))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.ARMOR_BREAK))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.STEEL_CYCLONE))

        player:clearTrusts()
        player:setLevel(5)
        trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 5, 'Must be lv 5')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.SHIELD_BREAK))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.ARMOR_BREAK))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.STEEL_CYCLONE))

        player:clearTrusts()
        player:setLevel(35)
        trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 35, 'Must be lv 35')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.ARMOR_BREAK))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.STEEL_CYCLONE))

        player:clearTrusts()
        player:setLevel(73)
        trustEntity = player:spawnTrust(xi.magic.spell.IRON_EATER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 73, 'Must be lv 73')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.STEEL_CYCLONE))
    end)
end)
