-- ZenithXI (modules\zenith-public\lua\4-additive\trusts\semih_lafihna_override.lua).
--
xi = xi or {}
xi.trustskills = xi.trustskills or {}

describe('Trust: SEMIH_LAFIHNA Integration Test #trusts #semih_lafihna', function()
    ---@type CClientEntityPair
    local player
    assert(xi.settings.map.TRUST_SKILLS_BY_LEVEL == true, 'Zenith: TRUST_SKILLS_BY_LEVEL Must be set to true')

    before_each(function()
        player = xi.test.world:spawnPlayer({ zone = xi.zone.WEST_RONFAURE, job = xi.job.WAR, level = 1 })
        player:setGMLevel(5)
    end)

    it('Trust skill check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.SEMIH_LAFIHNA)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(trustEntity:hasLearnedAbility(xi.ja.SHARPSHOT))
        assert(not trustEntity:hasLearnedAbility(xi.ja.BARRAGE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.DOUBLE_SHOT))
        -- assert(not trustEntity:hasLearnedAbility(xi.ja.STEALTH_SHOT))

        player:clearTrusts()
        player:setLevel(30)
        trustEntity = player:spawnTrust(xi.magic.spell.SEMIH_LAFIHNA)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 30, 'Must be lv 30')
        assert(trustEntity:hasLearnedAbility(xi.ja.SHARPSHOT))
        assert(trustEntity:hasLearnedAbility(xi.ja.BARRAGE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.DOUBLE_SHOT))
        -- assert(not trustEntity:hasLearnedAbility(xi.ja.STEALTH_SHOT))

        player:clearTrusts()
        player:setLevel(75)
        trustEntity = player:spawnTrust(xi.magic.spell.SEMIH_LAFIHNA)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 75, 'Must be lv 75')
        assert(trustEntity:hasLearnedAbility(xi.ja.SHARPSHOT))
        assert(trustEntity:hasLearnedAbility(xi.ja.BARRAGE))
        assert(trustEntity:hasLearnedAbility(xi.ja.DOUBLE_SHOT))
        -- assert(not trustEntity:hasLearnedAbility(xi.ja.STEALTH_SHOT))
    end)

    it('Trust trait check', function()
        local trustEntity = player:spawnTrust(xi.magic.spell.SEMIH_LAFIHNA)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(trustEntity:getMod(xi.mod.STORETP) == 40)
    end)

    it('Trust WS check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.SEMIH_LAFIHNA)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.FLAMING_ARROW))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.SIDEWINDER))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.STELLAR_ARROW))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.LUX_ARROW))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ARCHING_ARROW))

        player:clearTrusts()
        player:setLevel(5)
        trustEntity = player:spawnTrust(xi.magic.spell.SEMIH_LAFIHNA)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 5, 'Must be lv 5')
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.FLAMING_ARROW))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.SIDEWINDER))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.STELLAR_ARROW))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.LUX_ARROW))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ARCHING_ARROW))

        player:clearTrusts()
        player:setLevel(55)
        trustEntity = player:spawnTrust(xi.magic.spell.SEMIH_LAFIHNA)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 55, 'Must be lv 55')
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.FLAMING_ARROW))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.SIDEWINDER))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.STELLAR_ARROW))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.LUX_ARROW))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ARCHING_ARROW))

        player:clearTrusts()
        player:setLevel(66)
        trustEntity = player:spawnTrust(xi.magic.spell.SEMIH_LAFIHNA)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 66, 'Must be lv 66')
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.FLAMING_ARROW))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.SIDEWINDER))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.STELLAR_ARROW))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.LUX_ARROW))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ARCHING_ARROW))
    end)
end)
