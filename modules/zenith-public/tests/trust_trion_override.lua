describe('Trust: TRION Integration Test #trusts #trion', function()
    ---@type CClientEntityPair
    local player
    assert(xi.settings.map.TRUST_SKILLS_BY_LEVEL == true, 'Zenith: TRUST_SKILLS_BY_LEVEL Must be set to true')
    
    before_each(function()
        player = xi.test.world:spawnPlayer({ zone = xi.zone.WEST_RONFAURE, job = xi.job.WAR, level = 1 })
        player:setGMLevel(5)
    end)

    it('Trust spell check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasSpell(xi.magic.spell.CURE))
        assert(not trustEntity:hasSpell(xi.magic.spell.FLASH))
        assert(not trustEntity:hasSpell(xi.magic.spell.CURE_IV))

        player:clearTrusts()
        player:setLevel(45)
        trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 45, 'Must be lv 45')
        assert(trustEntity:hasSpell(xi.magic.spell.CURE))
        assert(trustEntity:hasSpell(xi.magic.spell.FLASH))
        assert(not trustEntity:hasSpell(xi.magic.spell.CURE_IV))

        player:clearTrusts()
        player:setLevel(55)
        trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 55, 'Must be lv 55')
        assert(trustEntity:hasSpell(xi.magic.spell.CURE))
        assert(trustEntity:hasSpell(xi.magic.spell.FLASH))
        assert(trustEntity:hasSpell(xi.magic.spell.CURE_IV))
    end)

    it('Trust skill check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.SENTINEL))

        
        player:clearTrusts()
        player:setLevel(5)
        trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 5, 'Must be lv 5')
        assert(not trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.SENTINEL))

        player:clearTrusts()
        player:setLevel(25)
        trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 25, 'Must be lv 25')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.SENTINEL))

        player:clearTrusts()
        player:setLevel(35)
        trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 35, 'Must be lv 35')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(trustEntity:hasLearnedAbility(xi.ja.SENTINEL))
    end)

    it('Trust WS check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.FAST_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.RED_LOTUS_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.FLAT_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.SAVAGE_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ROYAL_BASH))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ROYAL_SAVIOR))

        player:clearTrusts()
        player:setLevel(5)
        trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 5, 'Must be lv 5')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.FAST_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.RED_LOTUS_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.FLAT_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.SAVAGE_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ROYAL_BASH))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ROYAL_SAVIOR))

        
        player:clearTrusts()
        player:setLevel(40)
        trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 40, 'Must be lv 40')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.FAST_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.RED_LOTUS_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.FLAT_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.trustskills.id.SAVAGE_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ROYAL_BASH))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ROYAL_SAVIOR))


        player:clearTrusts()
        player:setLevel(75)
        trustEntity = player:spawnTrust(xi.magic.spell.TRION)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 75, 'Must be lv 75')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.FAST_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.RED_LOTUS_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.FLAT_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.SAVAGE_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ROYAL_BASH))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.ROYAL_SAVIOR))
    end)
end)