describe('Trust: VOLKER Integration Test #trusts #volker', function()
    ---@type CClientEntityPair
    local player
    assert(xi.settings.map.TRUST_SKILLS_BY_LEVEL == true, 'Zenith: TRUST_SKILLS_BY_LEVEL Must be set to true')
    
    before_each(function()
        player = xi.test.world:spawnPlayer({ zone = xi.zone.WEST_RONFAURE, job = xi.job.WAR, level = 1 })
        player:setGMLevel(5)
    end)

    it('Trust skill check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.DEFENDER))
        assert(not trustEntity:hasLearnedAbility(xi.ja.WARCRY))
        assert(not trustEntity:hasLearnedAbility(xi.ja.AGGRESSOR))
        assert(not trustEntity:hasLearnedAbility(xi.ja.RETALIATION))
        
        player:clearTrusts()
        player:setLevel(5)
        trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 5, 'Must be lv 5')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(not trustEntity:hasLearnedAbility(xi.ja.DEFENDER))
        assert(not trustEntity:hasLearnedAbility(xi.ja.WARCRY))
        assert(not trustEntity:hasLearnedAbility(xi.ja.AGGRESSOR))
        assert(not trustEntity:hasLearnedAbility(xi.ja.RETALIATION))

        player:clearTrusts()
        player:setLevel(25)
        trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 25, 'Must be lv 25')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(trustEntity:hasLearnedAbility(xi.ja.DEFENDER))
        assert(not trustEntity:hasLearnedAbility(xi.ja.WARCRY))
        assert(not trustEntity:hasLearnedAbility(xi.ja.AGGRESSOR))
        assert(not trustEntity:hasLearnedAbility(xi.ja.RETALIATION))

        player:clearTrusts()
        player:setLevel(35)
        trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 35, 'Must be lv 35')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(trustEntity:hasLearnedAbility(xi.ja.DEFENDER))
        assert(trustEntity:hasLearnedAbility(xi.ja.WARCRY))
        assert(not trustEntity:hasLearnedAbility(xi.ja.AGGRESSOR))
        assert(not trustEntity:hasLearnedAbility(xi.ja.RETALIATION))

        player:clearTrusts()
        player:setLevel(45)
        trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 45, 'Must be lv 45')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(trustEntity:hasLearnedAbility(xi.ja.DEFENDER))
        assert(trustEntity:hasLearnedAbility(xi.ja.WARCRY))
        assert(trustEntity:hasLearnedAbility(xi.ja.AGGRESSOR))
        assert(not trustEntity:hasLearnedAbility(xi.ja.RETALIATION))

        player:clearTrusts()
        player:setLevel(60)
        trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 60, 'Must be lv 60')
        assert(trustEntity:hasLearnedAbility(xi.ja.PROVOKE))
        assert(trustEntity:hasLearnedAbility(xi.ja.DEFENDER))
        assert(trustEntity:hasLearnedAbility(xi.ja.WARCRY))
        assert(trustEntity:hasLearnedAbility(xi.ja.AGGRESSOR))
        assert(trustEntity:hasLearnedAbility(xi.ja.RETALIATION))
    end)

    it('Trust WS check', function()
        -- Lv 1 check
        local trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 1, 'Must be lv 1')
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.FAST_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.RED_LOTUS_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.VORPAL_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.SPIRITS_WITHIN))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.SAVAGE_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(976))

        player:clearTrusts()
        player:setLevel(5)
        trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 5, 'Must be lv 5')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.FAST_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.RED_LOTUS_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.VORPAL_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.SPIRITS_WITHIN))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.SAVAGE_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(976))
        
        player:clearTrusts()
        player:setLevel(40)
        trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 40, 'Must be lv 40')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.FAST_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.RED_LOTUS_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.VORPAL_BLADE))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.SPIRITS_WITHIN))
        assert(not trustEntity:hasLearnedWeaponskill(xi.weaponskill.SAVAGE_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(976))

        player:clearTrusts()
        player:setLevel(75)
        trustEntity = player:spawnTrust(xi.magic.spell.VOLKER)
        assert(trustEntity ~= nil, 'Cannot be null')
        assert(trustEntity:getMainLvl() == 75, 'Must be lv 75')
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.FAST_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.RED_LOTUS_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.VORPAL_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.SPIRITS_WITHIN))
        assert(trustEntity:hasLearnedWeaponskill(xi.weaponskill.SAVAGE_BLADE))
        assert(trustEntity:hasLearnedWeaponskill(xi.trustskills.id.BERSERK_RUF))
    end)
end)